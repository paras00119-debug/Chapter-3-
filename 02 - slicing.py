a = "Paras yadav "
print(a[0:6]) #start from index 0 all the way till 6 (Postive Slicing)

print(a[-6:-0]) #start from index -6 all the way till -0 (negative Slicing)
print(a[:11]) #start from index 0 all the way till 10 (Postive Slicing)

# Skip Slicing
name = "Khushi prajapati"
print(name[2:5:1]) #start from index 2 all the way till 5 and skip 1 character
